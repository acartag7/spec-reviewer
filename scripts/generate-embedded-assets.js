import { readdirSync, writeFileSync } from "node:fs";
import { dirname, extname, join, relative, resolve, sep } from "node:path";

const root = resolve(new URL("..", import.meta.url).pathname);
const distDir = join(root, "dist");
const outputPath = join(root, "build", "embedded-assets.ts");
const files = listFiles(distDir);

if (!files.some((path) => relative(distDir, path) === "index.html")) {
  throw new Error("Missing dist/index.html. Run the web build first.");
}

const imports = files.map((path, index) =>
  `import asset${index} from ${JSON.stringify(relative(dirname(outputPath), path).split(sep).join("/"))} with { type: "file" };`
);
const entries = files.map((path, index) => {
  const route = `/${relative(distDir, path).split(sep).join("/")}`;
  return `  [${JSON.stringify(route)}, { path: asset${index}, contentType: ${JSON.stringify(contentType(path))} }],`;
});

writeFileSync(outputPath, [
  "// Generated by scripts/generate-embedded-assets.js. Do not edit.",
  ...imports,
  "",
  "const assets = new Map<string, { path: string; contentType: string }>([",
  ...entries,
  "]);",
  "",
  "export function embeddedAsset(pathname: string): Response | null {",
  "  const route = pathname === \"/\" ? \"/index.html\" : pathname;",
  "  const asset = assets.get(route);",
  "  if (asset == null) return null;",
  "  return new Response(Bun.file(asset.path), { headers: { \"content-type\": asset.contentType } });",
  "}",
  "",
].join("\n"), "utf8");

console.log(`Embedded asset manifest contains ${files.length} files`);

function listFiles(dir) {
  return readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => a.name.localeCompare(b.name))
    .flatMap((entry) => {
      const path = join(dir, entry.name);
      return entry.isDirectory() ? listFiles(path) : [path];
    });
}

function contentType(path) {
  const types = new Map([
    [".css", "text/css; charset=utf-8"],
    [".html", "text/html; charset=utf-8"],
    [".js", "text/javascript; charset=utf-8"],
    [".svg", "image/svg+xml"],
    [".woff2", "font/woff2"],
  ]);
  return types.get(extname(path)) ?? "application/octet-stream";
}
